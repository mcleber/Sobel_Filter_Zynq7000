#!/usr/bin/env python3
"""
convert_pgm_to_c.py

PT: Converte uma imagem PGM (binaria, formato P5) em um header C contendo
    um array de bytes com os pixels, para embutir diretamente no firmware
    bare-metal (sem precisar de sistema de arquivos ou envio via UART).

EN: Converts a PGM image (binary, P5 format) into a C header containing a
    byte array with the pixel data, to embed directly into the bare-metal
    firmware (no filesystem or UART transfer required).

Usage / Uso:
    python3 convert_pgm_to_c.py <input.pgm> <output.h> [var_name]

Example / Exemplo:
    python3 convert_pgm_to_c.py cat.pgm test_image_data.h test_image
"""

import sys


def pgm_to_c_array(pgm_path, out_path, var_name="test_image"):
    # PT: Le o cabecalho e os dados binarios do PGM (formato P5)
    # EN: Reads the header and binary data from the PGM (P5 format)
    with open(pgm_path, 'rb') as f:
        magic = f.readline().strip()
        if magic != b'P5':
            raise ValueError(
                f"Formato invalido: esperado 'P5' (binario), encontrado '{magic.decode(errors='replace')}'. "
                f"Invalid format: expected 'P5' (binary), found '{magic.decode(errors='replace')}'."
            )

        # PT: Pula linhas de comentario (iniciadas com '#')
        # EN: Skip comment lines (starting with '#')
        line = f.readline()
        while line.startswith(b'#'):
            line = f.readline()

        width, height = map(int, line.split())
        maxval = int(f.readline())
        data = f.read(width * height)

        if len(data) != width * height:
            raise ValueError(
                f"Dados incompletos: esperado {width * height} bytes, lido {len(data)}. "
                f"Incomplete data: expected {width * height} bytes, read {len(data)}."
            )

    # PT: Escreve o header C com as dimensoes e o array de pixels
    # EN: Writes the C header with the dimensions and the pixel array
    guard = f"{var_name.upper()}_DATA_H"
    with open(out_path, 'w') as f:
        f.write(f"#ifndef {guard}\n")
        f.write(f"#define {guard}\n\n")
        f.write(f"/* Auto-generated by convert_pgm_to_c.py from '{pgm_path}' */\n")
        f.write(f"/* Gerado automaticamente por convert_pgm_to_c.py a partir de '{pgm_path}' */\n\n")
        f.write(f"#define {var_name.upper()}_WIDTH  {width}\n")
        f.write(f"#define {var_name.upper()}_HEIGHT {height}\n")
        f.write(f"#define {var_name.upper()}_MAXVAL {maxval}\n\n")
        f.write(f"static const unsigned char {var_name}[{width * height}] = {{\n")
        for i, byte in enumerate(data):
            f.write(f"{byte},")
            if (i + 1) % 20 == 0:
                f.write("\n")
        f.write("\n};\n\n")
        f.write(f"#endif /* {guard} */\n")

    print(f"OK: {pgm_path} ({width}x{height}) -> {out_path}")
    print(f"OK: {pgm_path} ({width}x{height}) -> {out_path}")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("Usage / Uso: python3 convert_pgm_to_c.py <input.pgm> <output.h> [var_name]")
        sys.exit(1)

    pgm_path = sys.argv[1]
    out_path = sys.argv[2]
    var_name = sys.argv[3] if len(sys.argv) > 3 else "test_image"

    pgm_to_c_array(pgm_path, out_path, var_name)
